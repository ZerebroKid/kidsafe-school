/**
 * Invite / teacher code generation + collision-retry.
 *
 * Alphabet is intentionally restricted to characters that survive being read
 * aloud, written on a whiteboard, or typed into a phone -- no `0/O`, no
 * `1/I/l`, no `B/8`. The remaining 32 chars give ~32^8 (1.1 trillion) unique
 * 8-char invite codes and ~32^6 (1 billion) unique 6-char teacher codes,
 * which is more than enough headroom even if every school in India onboarded
 * tomorrow.
 *
 * The collision-retry helper exists because Firestore does not enforce
 * uniqueness on a field; we have to query-then-write inside a transaction
 * or accept a tiny race window. For inviteCode / teacherCode we are willing
 * to retry up to N times because the collision probability per attempt is
 * negligible.
 */

import {HttpsError} from 'firebase-functions/v2/https';
import type {Firestore} from 'firebase-admin/firestore';

const ALPHABET = 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789';

function randomCode(length: number): string {
  let out = '';
  for (let i = 0; i < length; i++) {
    out += ALPHABET.charAt(Math.floor(Math.random() * ALPHABET.length));
  }
  return out;
}

/** 8-char school invite code. Shared admin -> principal AND principal -> parents/children. */
export function generateInviteCode(): string {
  return randomCode(8);
}

/** 6-char teacher code. Generated by principal, shared with teachers. */
export function generateTeacherCode(): string {
  return randomCode(6);
}

/**
 * Generate a code that does not collide with any existing doc's `field` in
 * `collection`. Cheap query-per-attempt, retried up to `max` times. Throws
 * `HttpsError('internal', ...)` if we exhaust attempts (impossible in
 * practice for a 32^8 alphabet but defensible to catch a logic bug fast).
 *
 * The caller does the actual write -- this only produces the code. Keeping
 * the read + write separate makes the helper trivially testable without a
 * full Firestore transaction harness.
 */
export async function withCodeCollisionRetry(
  db: Firestore,
  collection: string,
  field: string,
  gen: () => string,
  max = 5,
): Promise<string> {
  for (let i = 0; i < max; i++) {
    const candidate = gen();
    const dup = await db
      .collection(collection)
      .where(field, '==', candidate)
      .limit(1)
      .get();
    if (dup.empty) return candidate;
  }
  throw new HttpsError(
    'internal',
    `Failed to generate a unique ${field} in ${collection} after ${max} attempts.`,
  );
}
