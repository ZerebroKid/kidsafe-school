/**
 * Education domain types for Phase 4.
 *
 * These mirror the Firestore schema documented in:
 *   - docs/EDUCATION_AI_TECH_SPEC.md §6 (onboarding) and §8 (data model)
 *   - docs/V2_BUILD_PHASES.md Group P4.2
 *
 * Consumed by:
 *   - apps/functions/* callables (claimSchool, approvePrincipal, requestTeacherJoin,
 *     approveTeacher, joinSchoolAsParent, joinSchool, importTopic, ...)
 *   - apps/admin-web (school CRUD, principal approval)
 *   - apps/principal-web Zerebro Campus (class/subject CRUD, teacher approval, roster)
 *   - apps/guardian ZConnect (parent + teacher screens)
 *   - apps/kidsafe ZKid (study loop, quiz)
 *
 * Convention: all server-written timestamps use FirestoreFieldValueLike so the
 * web, react-native, and admin SDK callers can each pass their own serverTimestamp()
 * sentinel without us caring about token shape. Read paths get a Timestamp/number
 * back depending on the SDK -- consumers coerce at their own boundary.
 */

import type {FirestoreFieldValueLike} from './firestore';

// ---------------------------------------------------------------------------
// P4.2.1 -- School + Principal + Class + Subject
// ---------------------------------------------------------------------------

/**
 * `schools/{schoolId}` -- top-level school record.
 *
 * Created by the admin in Zerebro Admin (`createSchool` UI / direct write
 * gated by admin role). The auto-generated `inviteCode` is the SINGLE code
 * shared manually with the principal AND later re-shared by the principal
 * with parents/children (per §6.1 / §6.3 / §6.4 of the spec).
 *
 * The principal-only `teacherCode` is generated separately via `rotateTeacherCode`
 * and rotated whenever the principal wants to revoke outstanding shares.
 */
export interface SchoolDoc {
  id: string;
  name: string;
  city?: string;
  /**
   * Set by `approvePrincipal` callable. Null until the admin verifies a
   * principal claim. Schools may exist without a principal in the brief
   * window between admin creation and principal approval.
   */
  principalUid: string | null;
  /**
   * 8-char invite code. Shared MANUALLY by admin -> principal, and later by
   * principal -> parents/children. One-time at signup, sticky role thereafter.
   * Rotate via `rotateInviteCode` callable to revoke outstanding shares.
   */
  inviteCode: string;
  inviteCodeRotatedAt?: FirestoreFieldValueLike;
  /**
   * 6-char teacher code. Generated by the principal via `rotateTeacherCode`
   * and re-shared MANUALLY with teachers. Optional because a school may not
   * have rotated a teacher code yet (e.g. very fresh school).
   */
  teacherCode?: string;
  teacherCodeRotatedAt?: FirestoreFieldValueLike;
  createdAt: FirestoreFieldValueLike;
}

/**
 * `schools/{schoolId}/principals/{principalId}` -- principal claim record.
 *
 * Written by `claimSchool` (status='pending') and updated by `approvePrincipal`
 * (status='active' or 'rejected'). Approval is the trigger that appends
 * `'principal'` to `users/{userId}.roles` and sets `schools/{schoolId}.principalUid`.
 *
 * Each school is locked to ONE active principal at a time -- duplicate
 * claim attempts on a school that already has an active principal are
 * rejected by the callable with `failed-precondition`.
 */
export interface PrincipalDoc {
  userId: string;
  displayName: string;
  phone: string;
  status: 'pending' | 'active' | 'rejected';
  requestedAt: FirestoreFieldValueLike;
  approvedByUid?: string;
  approvedAt?: FirestoreFieldValueLike;
  rejectedReason?: string;
}

/**
 * `schools/{schoolId}/teachers/{teacherId}` -- teacher join record.
 *
 * Written by `requestTeacherJoin` (status='pending') and updated by
 * `approveTeacher` (status='active') or `rejectTeacher` (status='rejected').
 * Approval is the trigger that ARRAY-UNIONS `'teacher'` into
 * `users/{userId}.roles` -- never overwrites, so parent-teachers keep their
 * parent role and the RoleSwitcher pill appears for them automatically.
 *
 * `teacherId == userId` by construction (same trick PrincipalDoc uses):
 *   1. Guarantees one pending request per phone per school.
 *   2. Lets ZConnect's pending screen subscribe via
 *      `collectionGroup('teachers').where('userId','==',myUid).limit(1)`
 *      without first knowing the schoolId -- the cross-school rule in
 *      firestore/rules `/{path=**}/teachers/{teacherId}` allows the read
 *      because `resource.data.userId == myUid()`.
 *   3. Aligns with the rules' `belongsToSchool()` predicate at write
 *      time (the principal can read every teacher doc under their school).
 */
export interface TeacherDoc {
  userId: string;
  displayName: string;
  phone: string;
  status: 'pending' | 'active' | 'rejected';
  requestedAt: FirestoreFieldValueLike;
  approvedByUid?: string;
  approvedAt?: FirestoreFieldValueLike;
  rejectedReason?: string;
}

/**
 * `schools/{schoolId}/parents/{parentId}` -- parent join record.
 *
 * Written by `joinSchoolAsParent` callable in a single transaction together
 * with `users/{userId}.roles arrayUnion 'parent'` and
 * `users/{userId}.schoolIds arrayUnion schoolId`. UNLIKE principal/teacher
 * there is NO approval gate -- the role is granted in the same call (§14 of
 * the tech spec). So there is no `status` / `approvedBy*` / `rejectedReason`
 * field here; presence of the doc is itself the proof of membership.
 *
 * `parentId == userId` by construction (same trick PrincipalDoc / TeacherDoc
 * use): one doc per parent per school, idempotent writes, and the doc id is
 * trivially predictable for the admin web's per-school audit view.
 *
 * Read access (firestore/rules):
 *   - the parent themselves (`resource.data.userId == myUid()`)
 *   - admin users
 *   - NOT the principal -- principal-web does not show the parents list
 *     anywhere; parents audit lives in admin web only.
 */
export interface ParentDoc {
  userId: string;
  phone: string;
  displayName?: string;
  joinedAt: FirestoreFieldValueLike;
}

/**
 * `schools/{schoolId}/classes/{classId}` -- a single class section in a school.
 *
 * Created by the principal in Zerebro Campus. `teacherIds` and `studentChildUids`
 * are array-unioned by `approveTeacher` + `joinSchool` respectively. Reads
 * from this doc drive class-roster screens in Campus + the teacher's
 * "my classes" filter in ZConnect.
 */
export interface ClassDoc {
  grade: number;
  section: string;
  /** Human-readable label, e.g. "8A" or "10 - Science". Free text. */
  className: string;
  /**
   * Academic year identifier, e.g. "2026-27". Used to scope rosters when a
   * school rolls forward at the start of a new academic year (new class doc
   * per year so we never lose historical rosters).
   */
  academicYear: string;
  teacherIds: string[];
  /**
   * Child UIDs (auth user ids of ZKid children) array-unioned by `joinSchool`.
   * Note: this is the child's `users/{uid}`, NOT a `children/{id}` doc id.
   * The Phase 2 pairing-only fallback uses `children/{id}` -- those rare
   * cases are tracked separately via the teacher's manual roster tools.
   */
  studentChildUids: string[];
  createdAt: FirestoreFieldValueLike;
}

/**
 * `schools/{schoolId}/classes/{classId}/subjects/{subjectId}` -- a subject taught in a class.
 *
 * Each subject pins a single `curriculumId` (-> `curriculum/{curriculumId}`)
 * so the teacher's "topic library" UI knows which curated content to pull.
 *
 * `teacherIds` is array-unioned when a teacher is granted access to teach a
 * subject in a class (Phase 4 ships subject-level teacher assignment in the
 * principal's class detail screen).
 */
export interface SubjectDoc {
  name: string;
  /** Optional short code, e.g. "PHY", "MATH". Display-only. */
  code?: string;
  curriculumId: string;
  teacherIds: string[];
}

// ---------------------------------------------------------------------------
// P4.2.2 -- Curriculum + Chapter + Topic content
// ---------------------------------------------------------------------------

/**
 * `curriculum/{curriculumId}` -- top-level curriculum record.
 *
 * `curriculumId` is a stable, human-readable slug like `cbse_8_science` so
 * subjects can reference it without follow-up reads. Created and maintained
 * by the content team via the `importTopic` script + admin tools.
 *
 * `board` is open-ended (string fallback) because state boards vary widely;
 * the three named values cover ~95% of real data.
 */
export interface CurriculumDoc {
  id: string;
  board: 'cbse' | 'icse' | 'state' | string;
  grade: number;
  subject: string;
}

/**
 * `curriculum/{curriculumId}/chapters/{chapterId}` -- a single chapter within a curriculum.
 *
 * `status` is the publish gate -- the topic-learn screens in ZKid filter to
 * `published` only; `draft` is what the content team writes against before
 * promoting to `published` in bulk.
 */
export interface ChapterDoc {
  chapterNo: number;
  chapterName: string;
  status: 'draft' | 'published';
}

/**
 * Single MCQ embedded inside `TopicContent.quiz[]`.
 *
 * Phase 4 ships MCQ only (type pinned to `'mcq'`). Other question types
 * (multi-select, free-text, match-the-following) are explicitly out of scope
 * for the MVP -- the type literal is intentionally narrow so introducing
 * new question types later is a typed, breaking-on-purpose change.
 */
export interface QuizQuestion {
  questionId: string;
  type: 'mcq';
  question: string;
  options: string[];
  /** Zero-based index into `options`. Validators MUST check 0 <= correctIndex < options.length. */
  correctIndex: number;
  explanation?: string;
}

/**
 * Single brainstorming card embedded inside `TopicContent.brainstorming[]`.
 *
 * Brainstorming cards are open-ended Q&A nudges shown alongside the main
 * explanation -- they're not graded, they're not part of the quiz. Optional
 * `videoUrl` is a curated YouTube link (admin-approved set only -- see §8.3
 * of the spec for the allow-listed source list).
 */
export interface BrainstormingItem {
  question: string;
  answer: string;
  videoUrl?: string;
}

/**
 * `curriculum/{curriculumId}/chapters/{chapterId}/topics/{topicId}` -- full curated
 * topic content (explanation + examples + brainstorming + quiz).
 *
 * No AI generation -- content team prepares JSON offline, engineering imports
 * via the `importTopic` script (Phase 4 chunk P4.6). `curatedBy` records the
 * human curator's user UID for audit, and `publishedAt` is set when the
 * content team flips `status` from `'draft'` to `'published'`.
 *
 * `videoUrl` (top-level) is the canonical "intro video" for the topic; each
 * `BrainstormingItem` may also link its own followup video. Both must come
 * from the admin-approved YouTube source list.
 */
export interface TopicContent {
  curriculumId: string;
  grade: number;
  subject: string;
  chapterNo: number;
  chapterName: string;
  topicId: string;
  topicName: string;
  explanation: string;
  examples: string[];
  videoUrl?: string;
  brainstorming: BrainstormingItem[];
  quiz: QuizQuestion[];
  status: 'draft' | 'published';
  /** UID of the human content curator who wrote this topic. */
  curatedBy: string;
  publishedAt?: FirestoreFieldValueLike;
}

// ---------------------------------------------------------------------------
// P4.5.1 -- StudyAssignment (teacher -> class topic assignment)
// ---------------------------------------------------------------------------

/**
 * `studyAssignments/{id}` -- TOP-LEVEL doc written exclusively by the
 * `assignTopic` callable via Admin SDK (firestore/rules blocks all client
 * writes -- only Admin SDK can create / update / delete).
 *
 * Doc id is DETERMINISTIC: `{classId}_{topicId}_{assignedDate}` where
 * `assignedDate` is the YYYY-MM-DD of the assignment in the school's TZ
 * (Asia/Kolkata for the MVP). The id lets the callable hard-block
 * duplicate same-day assignments inside the transaction with a single
 * point read instead of a query.
 *
 * Field naming aligns with the already-deployed rules (P3.4.2):
 *   - `assignedByTeacherUid` (NOT `assignedByTeacherId`) -- the rules at
 *     `match /studyAssignments/{id}` read `resource.data.assignedByTeacherUid`
 *     to grant the teacher self-read; changing the field name would silently
 *     break that rule.
 *
 * Denormalisation: `topicName` and `curriculumId` are copied onto the
 * assignment doc so list UIs (teacher home, ZKid Study Mission) can render
 * a card with one query instead of a fan-out read per assignment.
 *
 * `status` is `'active'` on creation; `'cancelled'` is reserved for a
 * future cancel flow (not built in P4.5). The callable treats a stale
 * `cancelled` doc with the same id as overwritable -- a teacher can
 * re-assign the same topic on the same day after cancelling.
 */
export interface StudyAssignmentDoc {
  /** Same value as the Firestore doc id. Denormalised so list reads don't need `snap.id`. */
  id: string;
  schoolId: string;
  classId: string;
  /** Doc id in the global `curriculum` collection (e.g. `cbse_8_science`). */
  curriculumId: string;
  /** Human-readable subject name from `curriculum/{curriculumId}.subject`. */
  subjectName: string;
  chapterId: string;
  topicId: string;
  /** Denormalised from `curriculum/.../topics/{topicId}.topicName` at write time. */
  topicName: string;
  /** Auth uid of the teacher who issued the assignment. Matches the firestore/rules predicate. */
  assignedByTeacherUid: string;
  /** Optional display name -- best effort copy from the active teacher doc; absent if missing. */
  assignedByTeacherDisplayName?: string;
  /** `YYYY-MM-DD` in the school TZ (Asia/Kolkata for MVP). Part of the deterministic doc id. */
  assignedDate: string;
  /** Server-stamped on create/overwrite. */
  assignedAt: FirestoreFieldValueLike;
  /** Epoch ms in UTC. Enforced by the callable to be >= now AND <= now + 30d. */
  dueAt: number;
  status: 'active' | 'cancelled';
}

/**
 * Input contract for the `assignTopic` callable. Mirrored on both the
 * client side (`callFn<AssignTopicInput, AssignTopicOutput>(...)`) and the
 * server side. `dueAt` is epoch ms in UTC; the client should default it
 * to today 23:59 in the teacher's TZ.
 */
export interface AssignTopicInput {
  schoolId: string;
  classId: string;
  curriculumId: string;
  chapterId: string;
  topicId: string;
  dueAt: number;
}

export interface AssignTopicOutput {
  assignmentId: string;
  /**
   * Always `false` from the production callable -- duplicate same-day
   * assignments throw `failed-precondition` instead of returning a
   * pre-existing id (locked decision in the P4.5 plan: hard-block dups).
   * Kept on the contract so a future `force=true` override stays a
   * non-breaking change.
   */
  alreadyExisted: boolean;
}

// ---------------------------------------------------------------------------
// P4.9 -- Quiz attempt (submitQuizAttempt callable)
// ---------------------------------------------------------------------------

/**
 * A single answer the child submits for one quiz question. The server NEVER
 * trusts `selectedIndex` for the score -- it re-grades against the topic doc's
 * `quiz[].correctIndex`. This shape is only the raw selection.
 */
export interface QuizAnswerInput {
  questionId: string;
  /** Zero-based index into the question's `options[]`. */
  selectedIndex: number;
}

/**
 * Input contract for the `submitQuizAttempt` callable. The child sends only
 * the assignment id + their raw selections; everything else (topic, school,
 * class, grading) is resolved server-side from the assignment.
 */
export interface SubmitQuizAttemptInput {
  assignmentId: string;
  answers: QuizAnswerInput[];
}

/**
 * Per-question grading result returned to the client so the result screen can
 * render a correct/wrong breakdown WITHOUT a second Firestore read. Includes
 * `correctIndex` + `explanation` (already readable in the topic doc anyway).
 */
export interface QuizQuestionResult {
  questionId: string;
  /** What the child picked (-1 if they left it blank / sent an out-of-range value). */
  selectedIndex: number;
  correctIndex: number;
  isCorrect: boolean;
  explanation?: string;
}

/**
 * Output of `submitQuizAttempt`. `passed` uses the locked 60% threshold. The
 * result screen renders entirely from this payload.
 */
export interface SubmitQuizAttemptOutput {
  attemptId: string;
  score: number;
  total: number;
  /** Integer 0-100, rounded. */
  percentage: number;
  passed: boolean;
  /** True only on the attempt that first crossed the pass threshold. */
  firstPass: boolean;
  results: QuizQuestionResult[];
}

/**
 * `quizAttempts/{assignmentId}_{childUid}` -- ONE doc per (assignment, child),
 * written exclusively by the `submitQuizAttempt` callable (Admin SDK). The
 * deterministic id makes retakes an idempotent upsert: each submit bumps
 * `attemptCount`, refreshes the `last*` fields, keeps the `best*` high-water
 * mark, and flips `passed` sticky-true once any attempt clears 60%.
 *
 * Field naming aligns with firestore/rules `match /quizAttempts/{id}`:
 *   - `childUid` (child self-read + parent `isOwnChild` read)
 *   - `assignedByTeacherUid` (teacher self-read)
 *   - `schoolId` (principal `belongsToSchool` read)
 */
export interface QuizAttemptDoc {
  /** Same value as the Firestore doc id (`{assignmentId}_{childUid}`). */
  id: string;
  assignmentId: string;
  schoolId: string;
  classId: string;
  curriculumId: string;
  chapterId: string;
  topicId: string;
  /** Denormalised from the assignment for report UIs. */
  topicName: string;
  /** Denormalised from the assignment; lowercased copy in `subjectTag` drives reward matching. */
  subjectName: string;
  childUid: string;
  /** Best-effort copy of `users/{childUid}.parentUid`; absent if the child has no linked parent. */
  parentUid?: string;
  /** Copied from the assignment so the teacher self-read rule resolves. */
  assignedByTeacherUid: string;
  /** `YYYY-MM-DD` (school TZ) copied from the assignment. */
  assignedDate: string;
  /** Number of questions graded (denominator). */
  total: number;
  /** How many times this child has submitted this assignment's quiz. */
  attemptCount: number;
  /** Most recent attempt. */
  lastScore: number;
  lastPercentage: number;
  lastAnswers: QuizAnswerInput[];
  /** High-water mark across all attempts. */
  bestScore: number;
  bestPercentage: number;
  /** Sticky once any attempt clears the 60% threshold. */
  passed: boolean;
  /** Server-stamped the first time `passed` flips true. Drives the reward trigger. */
  firstPassedAt?: FirestoreFieldValueLike;
  createdAt: FirestoreFieldValueLike;
  updatedAt: FirestoreFieldValueLike;
}

// ---------------------------------------------------------------------------
// P4.10 -- Reward catalog + reward unlock
// ---------------------------------------------------------------------------

export type RewardType = 'youtube_link' | 'game_link' | 'article_link';
export type RewardModerationStatus = 'pending' | 'approved' | 'rejected';

/**
 * `rewardCatalog/{rewardId}` -- admin-curated reward pool. Written by the
 * admin web (`isAdmin()` rule); read by signed-in clients ONLY when
 * `moderationStatus == 'approved'` (firestore/rules) and by the
 * `onQuizAttemptWrite` trigger via Admin SDK.
 *
 * MVP eligibility (locked decision): the reward picker matches on
 * `subjectTags array-contains <subject>` + `moderationStatus == 'approved'`
 * only -- no age/grade filtering yet. `subjectTags` MUST be stored lowercased
 * so the trigger's lowercased `array-contains` lookup matches.
 */
export interface RewardDoc {
  id: string;
  type: RewardType;
  title: string;
  /** Reward destination. youtube_link -> in-app player; others -> sandboxed in-app webview. */
  url: string;
  /** Lowercased subject keys (e.g. ["science"]). Matched against the topic's subject. */
  subjectTags: string[];
  moderationStatus: RewardModerationStatus;
  /** Admin uid who set `moderationStatus` to approved/rejected. */
  approvedBy?: string;
  createdAt: FirestoreFieldValueLike;
}

/**
 * `rewardUnlocks/{attemptId}` -- written exclusively by the
 * `onQuizAttemptWrite` trigger (Admin SDK) the first time a child passes a
 * given assignment's quiz. Doc id == the quiz attempt id so the write is
 * idempotent across trigger re-fires. Reward fields are denormalised so ZKid
 * can render the unlock without a follow-up `rewardCatalog` read.
 *
 * firestore/rules `match /rewardUnlocks/{id}` reads `childUid` for the child
 * self-read + parent `isOwnChild` read.
 */
export interface RewardUnlockDoc {
  /** Same value as the Firestore doc id (== the quiz attempt id). */
  id: string;
  attemptId: string;
  childUid: string;
  parentUid?: string;
  schoolId: string;
  classId: string;
  topicId: string;
  rewardId: string;
  /** Denormalised reward snapshot for ZKid rendering. */
  rewardType: RewardType;
  rewardTitle: string;
  rewardUrl: string;
  unlockedAt: FirestoreFieldValueLike;
}
